"""Generate ``src/memry/backends/_fts5_unicode.py`` from SQLite's own source.

FTS5's ``unicode61`` tokenizer decides what a word is from tables generated
out of the Unicode Character Database (``ext/fts5/fts5_unicode2.c``). The
portable keyword index (``memry.backends.keyword``) must split and fold text
exactly as FTS5 does, or its BM25 scores drift from ``bm25()``'s, so it uses
the same tables, copied here rather than re-derived from Python's
``unicodedata`` (which follows a newer Unicode version than SQLite's tables).

    curl -fsSLO https://raw.githubusercontent.com/sqlite/sqlite/version-3.53.1/ext/fts5/fts5_unicode2.c
    python tools/gen_fts5_unicode.py fts5_unicode2.c 3.53.1
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "memry" / "backends" / "_fts5_unicode.py"


def _body(src: str, name: str) -> str:
    match = re.search(rf"\b{name}\[\]\s*=\s*\{{(.*?)\}};", src, re.S)
    if not match:
        raise SystemExit(f"array {name} not found")
    return match.group(1)


def _ints(src: str, name: str) -> list[int]:
    return [int(x) for x in re.findall(r"\d+", _body(src, name))]


def _chars(src: str, name: str) -> list[int]:
    out = []
    for item in re.findall(r"'(\\0|.)'(\|HIBIT)?", _body(src, name)):
        char, hibit = item
        value = 0 if char == "\\0" else ord(char)
        out.append(value | (0x80 if hibit else 0))
    return out


def _entries(src: str) -> list[tuple[int, int, int]]:
    body = _body(src, "aEntry")
    return [tuple(int(v) for v in t) for t in re.findall(r"\{(\d+),\s*(\d+),\s*(\d+)\}", body)]


def _mask(src: str, name: str) -> int:
    match = re.search(rf"{name}\s*=\s*(0x[0-9A-Fa-f]+)", src)
    if not match:
        raise SystemExit(f"mask {name} not found")
    return int(match.group(1), 16)


def _categories(src: str) -> dict[str, int]:
    """Category name -> index into the tokenizer's category array, read from
    ``sqlite3Fts5UnicodeCatParse``."""
    body = src[src.index("int sqlite3Fts5UnicodeCatParse"):]
    body = body[: body.index("\n}\n")]
    out: dict[str, int] = {}
    major = None
    for line in body.splitlines():
        top = re.match(r"\s*case '([A-Z])':\s*$", line)
        if top:
            major = top.group(1)
            continue
        minor = re.match(r"\s*case '([a-zA-Z])': aArray\[(\d+)\] = 1; break;", line)
        if minor and major:
            out[major + minor.group(1)] = int(minor.group(2))
    return out


def _fmt(name: str, values: list, per_line: int = 12) -> str:
    rows = [", ".join(str(v) for v in values[i:i + per_line])
            for i in range(0, len(values), per_line)]
    return f"{name} = (\n" + "".join(f"    {row},\n" for row in rows) + ")\n"


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src = Path(sys.argv[1]).read_text()
    version = sys.argv[2]
    entries = _entries(src)
    parts = [
        '"""FTS5 unicode61 tables, generated by tools/gen_fts5_unicode.py from SQLite '
        f'{version}\'s\next/fts5/fts5_unicode2.c. Do not edit."""\n\n',
        f'SQLITE_VERSION = "{version}"\n\n',
        _fmt("DIA", _ints(src, "aDia")),
        _fmt("DIA_CHAR", _chars(src, "aChar")),
        _fmt("FOLD_CODE", [e[0] for e in entries]),
        _fmt("FOLD_FLAGS", [e[1] for e in entries]),
        _fmt("FOLD_RANGE", [e[2] for e in entries]),
        _fmt("FOLD_OFFSET", _ints(src, "aiOff")),
        _fmt("CAT_BLOCK", _ints(src, "aFts5UnicodeBlock")),
        _fmt("CAT_MAP", _ints(src, "aFts5UnicodeMap")),
        _fmt("CAT_DATA", _ints(src, "aFts5UnicodeData")),
        f"DIACRITIC_MASK0 = {_mask(src, 'mask0'):#010x}\n",
        f"DIACRITIC_MASK1 = {_mask(src, 'mask1'):#010x}\n",
        f"CATEGORY_INDEX = {_categories(src)!r}\n",
    ]
    OUT.write_text("".join(parts))
    print(f"wrote {OUT} ({len(entries)} fold rules)")


if __name__ == "__main__":
    main()
